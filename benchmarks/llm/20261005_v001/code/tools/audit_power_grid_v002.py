#!/usr/bin/env python3
"""Audit sealed grid screen/confirmation evidence without executing kernels.

Version 002 independently replays per-scope terminal status in candidate attempts.
The v001 auditor and all benchmark evidence remain unchanged.

Only Python's standard library is used. Compile, memory and numerical failures
are valid scientific outcomes; absent, corrupt or inconsistent evidence fails
this audit. This does not certify hardware peak memory or universal accuracy.
Bootstrap point ratios, round provenance and interval transformations are
checked; NumPy PCG64 bootstrap samples are not regenerated by this stdlib audit.
"""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import hashlib
import itertools
import json
import math
from pathlib import Path
import statistics


FAMILIES = ("native", "cubic", "strassen")
SCOPES = ("call", "prepared_kernel")
FIELDS = ("candidate_id", "algorithm", "variant", "tile", "compiler_options")
EXPECTED_BUDGETS = {"native": 4, "cubic": 24, "strassen": 24}
NATIVE_OPTION = "xla_tpu_scoped_vmem_limit_kib"


def finite(value, positive=False):
    return (type(value) in (int, float) and math.isfinite(value)
            and (not positive or value > 0))


def close(left, right):
    return finite(left) and finite(right) and math.isclose(left, right, rel_tol=1e-9, abs_tol=1e-10)


def spec(candidate):
    return {key: candidate.get(key, {} if key == "compiler_options" else None) for key in FIELDS}


def sha(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 ** 2), b""):
            digest.update(chunk)
    return digest.hexdigest()


def save(path, value):
    with Path(path).open("x", encoding="utf-8") as stream:
        json.dump(value, stream, indent=2, sort_keys=True, allow_nan=False)
        stream.write("\n")


class Checks:
    def __init__(self):
        self.counts = Counter()
        self.issues = []
        self.verified_files = {}

    def require(self, condition, code, detail):
        self.counts[code] += 1
        if not condition:
            self.issues.append({"code": code, "detail": str(detail)})
        return bool(condition)

    def load(self, path):
        try:
            value = json.loads(Path(path).read_text())
        except (OSError, ValueError) as error:
            self.require(False, "read_json", f"{path}: {type(error).__name__}: {error}")
            return None
        self.require(True, "read_json", path)
        return value

    def verify(self, directory, records, label):
        directory = Path(directory).resolve()
        if not self.require(isinstance(records, dict) and bool(records), "hash_inventory", label):
            return
        for name, record in records.items():
            expected = record if isinstance(record, str) else record.get("sha256") if isinstance(record, dict) else None
            path = (directory / name).resolve()
            if not self.require(path.is_relative_to(directory) and path.is_file(), "sealed_file_exists", f"{label}:{name}"):
                continue
            if not self.require(isinstance(expected, str) and len(expected) == 64, "sha256_format", f"{label}:{name}"):
                continue
            try:
                actual = sha(path)
            except OSError as error:
                self.require(False, "sealed_file_readable", f"{path}: {error}")
                continue
            self.require(actual == expected, "sealed_sha256", f"{label}:{name}")
            if isinstance(record, dict) and "bytes" in record:
                self.require(path.stat().st_size == record["bytes"], "sealed_byte_count", f"{label}:{name}")
            self.verified_files[str(path)] = actual


def resolve_benchmark_directory(path, checks):
    """Accept a canonical benchmark directory or an enclosing archive root."""
    path = Path(path).resolve()
    if (path / "artifacts/results.jsonl").is_file():
        outer_seal = checks.load(path / "artifact-manifest.json")
        if outer_seal is not None:
            checks.verify(path, outer_seal, f"{path.name}:outer_artifacts")
        outer_source = checks.load(path / "source-manifest.json")
        if outer_source:
            checks.verify(path / "source", outer_source.get("source_sha256"), f"{path.name}:outer_source")
            archive = path / "source.tar"
            checks.require(archive.is_file() and sha(archive) == outer_source.get("archive_sha256"),
                           "source_archive_sha256", str(archive))
        return path / "artifacts"
    if (path / "results.jsonl").is_file():
        return path
    checks.require(False, "benchmark_directory", f"No results.jsonl in {path} or its artifacts directory")
    return path


def rows_by_key(rows):
    result = defaultdict(list)
    for row in rows:
        result[(row.get("group_id"), row.get("arm_id"), row.get("scope"))].append(row)
    return result


def numerical_contract(row, shape, campaign, checks, context):
    metrics = row.get("correctness")
    status = row.get("status")
    if status in ("ok", "numerical_failure"):
        checks.require(isinstance(metrics, dict), "numerical_metrics_present", context)
    if not isinstance(metrics, dict):
        return
    if metrics.get("finite") is True:
        checks.require(all(finite(metrics.get(key)) and metrics[key] >= 0
                           for key in ("relative_l2", "max_abs_error", "max_abs_reference")),
                       "nonnegative_error_metrics", context)
    gate = campaign["correctness"]["gate"]
    gated = (metrics.get("finite") is True and finite(metrics.get("relative_l2"))
             and finite(metrics.get("max_abs_error")) and finite(metrics.get("max_abs_reference"))
             and metrics["relative_l2"] <= gate["relative_l2_max"]
             and metrics["max_abs_error"] <= gate["max_abs_atol"] + gate["max_abs_reference_rtol"] * metrics["max_abs_reference"])
    checks.require(metrics.get("pass") is gated, "numerical_gate_recomputed", context)
    if status == "ok":
        checks.require(gated, "eligible_numerical_gate", context)
    if status == "numerical_failure":
        checks.require(not gated, "failure_numerical_gate", context)
    ref_scope = metrics.get("reference_scope")
    checks.require(ref_scope in ("full", "sampled_cross_product"), "reference_scope", context)
    checks.require(metrics.get("all_k_used") == shape["k"], "reference_uses_all_k", context)
    checks.require(metrics.get("reference_input_dtype") == "quantized_bf16"
                   and metrics.get("reference_accumulation_dtype") == "float32",
                   "reference_arithmetic", context)
    indices = []
    for axis, key in (("m", "sample_rows"), ("n", "sample_columns")):
        values = metrics.get(key)
        valid = (isinstance(values, list) and bool(values)
                 and all(type(v) is int and 0 <= v < shape[axis] for v in values)
                 and values == sorted(set(values)))
        checks.require(valid, "reference_sample_indices", f"{context}:{axis}")
        if valid:
            checks.require(values[0] == 0 and values[-1] == shape[axis] - 1,
                           "reference_includes_boundaries", f"{context}:{axis}")
            if ref_scope == "full":
                checks.require(len(values) == shape[axis], "full_reference_extent", f"{context}:{axis}")
            indices.append(values)
    if len(indices) == 2:
        checks.require(metrics.get("sample_count") == len(indices[0]) * len(indices[1]),
                       "reference_cross_product_size", context)


def timing_contract(row, raw, repeats, checks, context):
    rounds = [sample.get("round") for sample in raw]
    checks.require(len(rounds) == len(set(rounds)) and all(type(r) is int and 0 <= r < repeats for r in rounds),
                   "raw_round_ids", context)
    times = [sample.get("elapsed_ms") for sample in raw]
    checks.require(all(finite(value, positive=True) for value in times), "raw_positive_latency", context)
    timing = row.get("timing") or {}
    if row.get("status") == "ok":
        checks.require(set(rounds) == set(range(repeats)) and len(raw) == repeats,
                       "eligible_sample_count", context)
    if timing:
        checks.require(timing.get("sample_count") == len(raw), "timing_sample_count", context)
        if times and all(finite(v, positive=True) for v in times):
            expected = {"mean_ms": statistics.fmean(times), "median_ms": statistics.median(times),
                        "min_ms": min(times), "max_ms": max(times),
                        "std_ms": statistics.stdev(times) if len(times) > 1 else 0.0}
            for key, value in expected.items():
                checks.require(close(timing.get(key), value), "timing_statistic", f"{context}:{key}")
    elif raw:
        checks.require(False, "timing_summary_present", context)


def pair_contract(pair, left, right, checks, context, *, inverse=False):
    """Check same-group round provenance and point ratio, not PCG64 CI draws."""
    left_rounds = {sample["round"]: sample["elapsed_ms"] for sample in left}
    right_rounds = {sample["round"]: sample["elapsed_ms"] for sample in right}
    common = sorted(left_rounds.keys() & right_rounds.keys())
    if not checks.require(bool(common), "paired_rounds_present", context):
        return
    if "paired_rounds" in pair:
        checks.require(pair["paired_rounds"] == common, "paired_round_identity", context)
    ratio = statistics.fmean(left_rounds[r] for r in common) / statistics.fmean(right_rounds[r] for r in common)
    field = "latency_ratio_to_frozen_winner" if inverse else "speedup_ratio_of_means"
    checks.require(close(pair.get(field), 1 / ratio if inverse else ratio), "paired_point_ratio", context)
    ci = pair.get("latency_ratio_ci95" if inverse else "speedup_ci95")
    checks.require(isinstance(ci, list) and len(ci) == 2 and all(finite(v, positive=True) for v in ci)
                   and ci[0] <= ci[1], "paired_interval_shape", context)
    if "time_reduction_fraction" in pair:
        checks.require(close(pair["time_reduction_fraction"], 1 - 1 / ratio), "paired_time_reduction", context)
    if inverse and isinstance(ci, list) and len(ci) == 2 and all(finite(v) for v in ci):
        checks.require(pair.get("certified_within_5_percent") is (ci[1] <= 1.05),
                       "near_interval_threshold", context)


def audit_phase(path, phase, manifest, checks):
    directory = resolve_benchmark_directory(path, checks)
    loaded = {name: checks.load(directory / name) for name in
              ("artifact_manifest.json", "source_manifest.json", "summary.json", "environment.json", "planned_cases.json")}
    seal = loaded["artifact_manifest.json"] or {}
    sources = loaded["source_manifest.json"] or {}
    checks.verify(directory, seal.get("sha256"), f"{phase}:artifact_manifest")
    checks.verify(directory, sources.get("sha256"), f"{phase}:source_manifest")
    for required in ("source_manifest.json", "summary.json", "environment.json", "planned_cases.json", "results.jsonl",
                     "selections.json" if phase == "GRID-screen" else "confirmation.json"):
        checks.require(required in seal.get("sha256", {}), "required_artifact_sealed", f"{phase}:{required}")
    config_candidates = []
    for file in sorted((directory / "config_snapshot").glob("*.json")):
        data = checks.load(file)
        if isinstance(data, dict) and "GRID-screen" in data.get("experiments", {}):
            config_candidates.append((file, data))
    if not checks.require(len(config_candidates) == 1, "campaign_snapshot_unique", phase):
        return None
    config_path, campaign = config_candidates[0]
    shape_snapshots = [file for file in (directory / "config_snapshot").glob("*.json")
                       if isinstance((data := checks.load(file)), dict) and data == manifest]
    checks.require(len(shape_snapshots) == 1, "supplied_manifest_in_sealed_snapshot", phase)
    environment = loaded["environment.json"] or {}
    checks.require(environment.get("qualified_single_v5e") is True
                   and environment.get("backend") == "tpu" and bool(environment.get("identity")),
                   "qualified_recorded_environment", phase)
    expected_precision = {"input_dtype": "bfloat16", "pre_add_dtype": "bfloat16",
                          "accumulator_dtype": "float32", "output_dtype": "float32", "native_precision": "DEFAULT"}
    checks.require(all(campaign.get("precision", {}).get(key) == value for key, value in expected_precision.items()),
                   "registered_arithmetic_contract", phase)
    experiment = campaign["experiments"][phase]
    checks.require(set(experiment["shape_ids"]) == set(manifest["exploratory_shape_ids"])
                   and len(experiment["shape_ids"]) == 60, "phase_exploratory_shapes", phase)
    checks.require(campaign["grid_study"]["reserved_holdout_shape_ids"] == manifest["holdout_shape_ids"],
                   "campaign_holdout_reservation", phase)
    checks.require(campaign["grid_study"].get("full_lattice_execution") is False, "sampled_not_full_lattice", phase)
    planned = loaded["planned_cases.json"] or []
    groups = {group["group_id"]: group for group in planned}
    checks.require(len(groups) == len(planned), "planned_group_unique", phase)
    shapes = {row["id"]: row for row in manifest["shapes"]}
    planned_cases = {}
    for group in planned:
        shape_id = group["shape"]["id"]
        checks.require(shape_id in manifest["exploratory_shape_ids"], "no_holdout_execution", group["group_id"])
        if shape_id not in shapes:
            continue
        checks.require(all(group["shape"].get(d) == shapes[shape_id][d] for d in ("m", "n", "k")),
                       "planned_named_geometry", group["group_id"])
        checks.require(group["scopes"] == list(SCOPES), "planned_timing_scopes", group["group_id"])
        checks.require(group.get("inputs") == [{"distribution": "gaussian", "seed": experiment.get("seed", campaign["seed"])}],
                       "planned_shared_input_contract", group["group_id"])
        for arm in group["arms"]:
            for scope in group["scopes"]:
                key = (group["group_id"], arm["arm_id"], scope)
                checks.require(key not in planned_cases, "planned_case_unique", key)
                planned_cases[key] = (group, arm)
    rows = []
    try:
        with (directory / "results.jsonl").open() as stream:
            for line_index, line in enumerate(stream, 1):
                try:
                    row = json.loads(line)
                except ValueError as error:
                    checks.require(False, "journal_parse", f"{phase}:{line_index}:{error}")
                    continue
                checks.require(row.get("sequence") == line_index, "journal_sequence", f"{phase}:{line_index}")
                checks.require(row.get("phase") == phase, "journal_phase", f"{phase}:{line_index}")
                rows.append(row)
    except OSError as error:
        checks.require(False, "journal_read", f"{phase}:{error}")
    case_rows = [row for row in rows if row.get("event") == "case_result"]
    cases = rows_by_key(case_rows)
    samples = rows_by_key([row for row in rows if row.get("event") == "sample"])
    compilations = rows_by_key([row for row in rows if row.get("event") == "compilation" and row.get("status") == "ok"])
    checks.require(set(cases) == set(planned_cases), "terminal_cases_match_plan", phase)
    checks.require(set(samples) <= set(planned_cases), "sample_cases_in_plan", phase)
    repeats = campaign["timing"][experiment["timing"]]["repeats"]
    checks.require(repeats == (7 if phase == "GRID-screen" else 30), "registered_repeats", phase)
    for row in rows:
        if row.get("shape_id"):
            checks.require(row["shape_id"] in manifest["exploratory_shape_ids"],
                           "no_holdout_observation", f"{phase}:{row['sequence']}")
        if row.get("group_id"):
            group = groups.get(row["group_id"])
            if not checks.require(group is not None, "journal_group_in_plan", f"{phase}:{row['sequence']}"):
                continue
            shape = group["shape"]
            checks.require(row.get("shape_id") == shape["id"] and row.get("shape_mkn") == [shape[d] for d in ("m", "k", "n")],
                           "journal_legacy_mkn_geometry", f"{phase}:{row['sequence']}")
            if row.get("arm_id"):
                arm = next((arm for arm in group["arms"] if arm["arm_id"] == row["arm_id"]), None)
                checks.require(arm is not None, "journal_arm_in_plan", f"{phase}:{row['sequence']}")
                if arm:
                    checks.require(row.get("family") == arm["family"] and spec(row) == spec(arm),
                                   "journal_candidate_spec", f"{phase}:{row['sequence']}")
            if row.get("event") == "compilation" and row.get("status") == "ok":
                checks.require((row.get("kernel_metadata") or {}).get("compiler_options", {}) == row.get("compiler_options", {}),
                               "compiled_options_metadata", f"{phase}:{row['sequence']}")
    native_statuses = defaultdict(Counter)
    for key, found in cases.items():
        if not checks.require(len(found) == 1, "terminal_case_unique", f"{phase}:{key}") or key not in planned_cases:
            continue
        row = found[0]
        group, arm = planned_cases[key]
        status = row.get("status")
        checks.require(isinstance(status, str) and bool(status), "terminal_status_present", f"{phase}:{key}")
        checks.require(row.get("eligible_for_speedup_claim") is (status == "ok"), "speedup_eligibility", f"{phase}:{key}")
        if status == "ok":
            checks.require(len(compilations.get(key, [])) == 1, "eligible_successful_compilation_recorded", f"{phase}:{key}")
        timing_contract(row, samples.get(key, []), repeats, checks, f"{phase}:{key}")
        numerical_contract(row, group["shape"], campaign, checks, f"{phase}:{key}")
        metadata = row.get("kernel_metadata")
        if status == "ok":
            checks.require(isinstance(metadata, dict), "eligible_kernel_metadata", f"{phase}:{key}")
        if isinstance(metadata, dict):
            shape_mkn = [group["shape"][d] for d in ("m", "k", "n")]
            padded_mkn = shape_mkn
            if arm.get("tile"):
                bm, bn, bk = arm["tile"]
                padded_mkn = [((size + block - 1) // block) * block
                              for size, block in zip(shape_mkn, (bm, bk, bn))]
            checks.require(metadata.get("shape_mkn") == shape_mkn and metadata.get("padded_shape_mkn") == padded_mkn,
                           "kernel_original_and_padded_geometry", f"{phase}:{key}")
            checks.require(metadata.get("algorithm") == arm["algorithm"] and metadata.get("variant") == arm["variant"]
                           and metadata.get("tile_bm_bn_bk") == arm.get("tile"),
                           "kernel_candidate_metadata", f"{phase}:{key}")
            checks.require(metadata.get("strassen_levels_per_tile") == (1 if arm["family"] == "strassen" else 0)
                           and metadata.get("input_dtype") == "bfloat16" and metadata.get("output_dtype") == "float32"
                           and metadata.get("accumulation_dtype") == "float32",
                           "kernel_arithmetic_and_level_metadata", f"{phase}:{key}")
        if arm["family"] == "native":
            native_statuses[arm["candidate_id"]][str(status)] += 1
        if status == "unsupported_compiler_option":
            checks.require(arm["family"] == "native" and bool(arm.get("compiler_options")),
                           "unsupported_option_candidate", f"{phase}:{key}")
        for pair in row.get("comparisons") or []:
            reference_key = (key[0], pair.get("reference_arm"), key[2])
            reference_rows = cases.get(reference_key, [])
            if checks.require(len(reference_rows) == 1, "comparison_reference_same_group", f"{phase}:{key}"):
                expected_valid = status == "ok" and reference_rows[0].get("status") == "ok"
                checks.require(pair.get("valid_numerical_comparison") is expected_valid,
                               "comparison_numerical_eligibility", f"{phase}:{key}")
                pair_contract(pair, samples.get(reference_key, []), samples.get(key, []), checks, f"{phase}:{key}")
    summary = loaded["summary.json"] or {}
    fingerprints = defaultdict(set)
    for row in rows:
        if row.get("event") == "case_start":
            fingerprint = row.get("input_fingerprint") or {}
            checks.require(fingerprint.get("quantized_dtype") == "bfloat16"
                           and all(isinstance(fingerprint.get(key), str) and len(fingerprint[key]) == 64
                                   for key in ("a_sha256", "b_sha256")), "quantized_input_fingerprint", f"{phase}:{row.get('group_id')}")
            fingerprints[row.get("shape_id")].add(json.dumps(fingerprint, sort_keys=True))
    for shape_id, values in fingerprints.items():
        checks.require(len(values) == 1, "same_inputs_across_candidate_batches", f"{phase}:{shape_id}")
    for event in ("group_start", "group_complete"):
        group_ids = [row.get("group_id") for row in rows if row.get("event") == event]
        checks.require(set(group_ids) == set(groups) and len(group_ids) == len(groups), "journal_group_lifecycle", f"{phase}:{event}")
    identities = [row for row in rows if row.get("event") == "identity_check"]
    checks.require(len(identities) == 1 and identities[0].get("status") == "matched", "journal_identity_matched", phase)
    counts = dict(Counter(str(row.get("status")) for row in case_rows))
    checks.require(summary.get("phase") == phase and summary.get("completed") is True,
                   "phase_complete_evidence", phase)
    checks.require(summary.get("case_status_counts") == counts, "summary_status_counts", phase)
    checks.require(summary.get("planned_group_count") == len(groups)
                   and set(summary.get("completed_groups", [])) == set(groups)
                   and not summary.get("not_completed_group_ids"), "summary_group_completion", phase)
    completion_rows = [row for row in rows if row.get("event") == "run_complete"]
    checks.require(len(completion_rows) == 1 and all(completion_rows[0].get(k) == v for k, v in summary.items()),
                   "journal_summary_agreement", phase)
    return {"directory": directory, "campaign_path": config_path, "campaign": campaign,
            "source_manifest": sources, "environment": loaded["environment.json"] or {},
            "planned": planned, "groups": groups, "planned_cases": planned_cases,
            "cases": cases, "case_rows": case_rows, "samples": samples,
            "report": {"phase": phase, "directory": str(directory), "case_count": len(case_rows),
                       "sample_count": sum(map(len, samples.values())), "planned_groups": len(groups),
                       "case_status_counts": counts,
                       "native_terminal_statuses_by_candidate": {k: dict(v) for k, v in native_statuses.items()},
                       "environment_identity": (loaded["environment.json"] or {}).get("identity")}}


def tile_projection(candidates):
    tuples = [list(row["tile"]) for row in candidates if row.get("tile") is not None]
    return {"tuples_bm_bn_bk": tuples,
            "axis_values": {axis: sorted({tile[i] for tile in tuples})
                            for i, axis in enumerate(("bm", "bn", "bk"))},
            "scope": "Discrete tested tuples only; axis projections do not certify their Cartesian product."}


def eligible_scopes(run, shape_id, family, candidate_id, group_id=None):
    found = [row for row in run["case_rows"] if row.get("shape_id") == shape_id
             and row.get("family") == family and row.get("candidate_id") == candidate_id
             and (group_id is None or row.get("group_id") == group_id)]
    by_scope = {row["scope"]: row for row in found}
    if len(found) != 2 or set(by_scope) != set(SCOPES):
        return None
    expected = 7 if run["report"]["phase"] == "GRID-screen" else 30
    for row in found:
        timing = row.get("timing") or {}
        if (row.get("status") != "ok" or (row.get("correctness") or {}).get("pass") is not True
                or timing.get("sample_count") != expected or not finite(timing.get("mean_ms"), positive=True)):
            return None
    return by_scope


def replay_selection(screen, manifest):
    """Independent stdlib replay of the frozen deterministic selection rules."""
    experiment = screen["campaign"]["experiments"]["GRID-screen"]
    policy = {"top_k": experiment.get("shortlist_top_k", 3),
              "near_fraction": experiment.get("near_optimal_fraction", .05),
              "max_confirm_per_family": experiment.get("shortlist_max_per_family", 6),
              **experiment.get("selection_policy", {})}
    shapes = {row["id"]: row for row in manifest["shapes"]}
    results = {}
    for shape_id in experiment["shape_ids"]:
        row = {"shape_mkn": [shapes[shape_id][d] for d in ("m", "k", "n")]}
        for family in FAMILIES:
            eligible, attempts = [], []
            for candidate in experiment["candidate_families"][family]:
                observed = eligible_scopes(screen, shape_id, family, candidate["candidate_id"])
                candidate_rows = [row for row in screen["case_rows"]
                                  if row.get("shape_id") == shape_id and row.get("family") == family
                                  and row.get("candidate_id") == candidate["candidate_id"]]
                scope_status = {scope: next((row.get("status") for row in candidate_rows
                                             if row.get("scope") == scope), "not_run") for scope in SCOPES}
                attempts.append({**spec(candidate), "eligible": observed is not None,
                                 "scope_status": scope_status})
                if observed:
                    eligible.append({**spec(candidate), "mean_ms": observed["call"]["timing"]["mean_ms"],
                                     "prepared_mean_ms": observed["prepared_kernel"]["timing"]["mean_ms"]})
            eligible.sort(key=lambda candidate: (candidate["mean_ms"], candidate["candidate_id"]))
            winner = eligible[0] if eligible else None
            near = [candidate for candidate in eligible if candidate["mean_ms"] <= winner["mean_ms"] * (1 + policy["near_fraction"])]
            desired = {candidate["candidate_id"] for candidate in eligible[:policy["top_k"]] + near}
            shortlist = [candidate for candidate in eligible if candidate["candidate_id"] in desired][:policy["max_confirm_per_family"]]
            confirmed = {candidate["candidate_id"] for candidate in shortlist}
            row[family] = {"winner": winner, "confirmation_candidates": shortlist,
                           "screen_eligible_candidates": eligible, "candidate_attempts": attempts,
                           "screen_near_candidates": [{**candidate, "scheduled_for_confirmation": candidate["candidate_id"] in confirmed}
                                                      for candidate in near],
                           "screen_near_tile_projection": tile_projection(near),
                           "near_status": "descriptive screen threshold; confirmation required"}
        results[shape_id] = row
    return results, policy


def audit_screen(screen, manifest, checks):
    directory = screen["directory"]
    selection = checks.load(directory / "selections.json")
    if not isinstance(selection, dict):
        return None
    experiment = screen["campaign"]["experiments"]["GRID-screen"]
    families = experiment["candidate_families"]
    budgets = {family: len(families[family]) for family in FAMILIES}
    checks.require(budgets == EXPECTED_BUDGETS, "screen_candidate_budgets", budgets)
    checks.require(len(screen["case_rows"]) == 60 * 52 * 2, "screen_6240_terminal_cases", len(screen["case_rows"]))
    counts = Counter((row.get("shape_id"), row.get("family"), row.get("candidate_id"), row.get("scope"))
                     for row in screen["case_rows"])
    expected = {(shape_id, family, candidate["candidate_id"], scope)
                for shape_id in manifest["exploratory_shape_ids"] for family in FAMILIES
                for candidate in families[family] for scope in SCOPES}
    checks.require(set(counts) == expected and all(count == 1 for count in counts.values()),
                   "screen_each_candidate_once_per_scope", "60 shapes × (4+24+24 candidates) ×2 scopes")
    for group in screen["planned"]:
        for arm in group["arms"]:
            allowed = {candidate["candidate_id"]: spec(candidate) for candidate in families[arm["family"]]}
            checks.require(spec(arm) == allowed.get(arm["candidate_id"]), "screen_registered_candidate", group["group_id"])
    checks.require(selection.get("phase") == "GRID-screen" and selection.get("stage") == "screen",
                   "selection_phase", directory)
    checks.require(selection.get("candidate_attempt_budgets") == budgets, "selection_budget_metadata", directory)
    checks.require(selection.get("environment_identity") == screen["environment"].get("identity"),
                   "selection_environment_identity", directory)
    for key, path in (("campaign_sha256", screen["campaign_path"]),
                      ("screen_results_sha256", directory / "results.jsonl"),
                      ("source_manifest_sha256", directory / "source_manifest.json")):
        checks.require(selection.get(key) == sha(path), "selection_provenance_sha256", key)
    results, policy = replay_selection(screen, manifest)
    checks.require(selection.get("by_shape") == results, "frozen_selection_replayed", directory)
    checks.require(selection.get("selection_policy") == policy, "frozen_selection_policy_replayed", directory)
    screen["report"]["eligible_candidates_by_family"] = {
        family: sum(len(row[family]["screen_eligible_candidates"]) for row in results.values()) for family in FAMILIES}
    return selection


def expected_confirmation_groups(selection, campaign, shape_ids):
    default = next(candidate for candidate in campaign["experiments"]["GRID-screen"]["candidate_families"]["native"]
                   if not candidate.get("compiler_options"))
    expected = {}
    for shape_id in shape_ids:
        row = selection["by_shape"][shape_id]
        headline = [(family, row[family]["winner"]) for family in FAMILIES if row[family].get("winner")]
        if default["candidate_id"] not in {candidate["candidate_id"] for _, candidate in headline}:
            headline.append(("native", default))
        expected[f"{shape_id}__headline_confirmation"] = headline
        for family in FAMILIES:
            winner = row[family].get("winner")
            if not winner:
                continue
            for candidate in row[family]["confirmation_candidates"]:
                if candidate["candidate_id"] == winner["candidate_id"]:
                    continue
                if family == "native" and candidate["candidate_id"] == default["candidate_id"]:
                    continue
                expected[f"{shape_id}__finalist_{family}_{candidate['candidate_id']}"] = [(family, winner), (family, candidate)]
    return expected


def candidate_samples(run, group_id, candidate_id, scope):
    group = run["groups"].get(group_id, {})
    arm = next((arm for arm in group.get("arms", []) if arm["candidate_id"] == candidate_id), None)
    return run["samples"].get((group_id, arm["arm_id"], scope), []) if arm else []


def audit_confirmation(screen, confirmation, selection, manifest, manifest_path, checks):
    directory = confirmation["directory"]
    report = checks.load(directory / "confirmation.json")
    frozen = checks.load(directory / "selection_input.json")
    provenance = checks.load(directory / "selection_input_provenance.json")
    checks.require(frozen == selection, "confirmation_exact_selection_copy", directory)
    checks.require((provenance or {}).get("sha256") == sha(screen["directory"] / "selections.json"),
                   "confirmation_selection_copy_sha256", directory)
    checks.require(screen["environment"].get("identity") == confirmation["environment"].get("identity"),
                   "screen_confirmation_same_environment", directory)
    checks.require(sha(screen["campaign_path"]) == sha(confirmation["campaign_path"]),
                   "screen_confirmation_same_campaign", directory)
    source_hashes = lambda run: {name: value for name, value in run["source_manifest"].get("sha256", {}).items()
                               if name.startswith("source_snapshot/")}
    checks.require(source_hashes(screen) == source_hashes(confirmation) and bool(source_hashes(screen)),
                   "screen_confirmation_same_source", directory)
    checks.require(selection.get("shape_manifest_sha256") == sha(manifest_path), "selection_supplied_shape_hash", manifest_path)
    expected = expected_confirmation_groups(selection, screen["campaign"], manifest["exploratory_shape_ids"])
    checks.require(set(confirmation["groups"]) == set(expected), "confirmation_groups_from_frozen_selection", directory)
    for group_id, intended in expected.items():
        observed = confirmation["groups"].get(group_id, {}).get("arms", [])
        checks.require([(arm["family"], spec(arm)) for arm in observed]
                       == [(family, spec(candidate)) for family, candidate in intended],
                       "confirmation_frozen_group_candidates", group_id)
    if not isinstance(report, dict):
        return
    checks.require(set(report.get("by_shape", {})) == set(manifest["exploratory_shape_ids"]),
                   "confirmation_report_shapes", directory)
    shapes = {row["id"]: row for row in manifest["shapes"]}
    verified_pairs = 0
    for shape_id, shape_report in report.get("by_shape", {}).items():
        if shape_id not in shapes or shape_id not in selection["by_shape"]:
            continue
        selected = selection["by_shape"][shape_id]
        checks.require(shape_report.get("shape_mkn") == [shapes[shape_id][d] for d in ("m", "k", "n")],
                       "confirmation_report_geometry", shape_id)
        for family in FAMILIES:
            family_report = shape_report.get(family, {})
            winner = selected[family].get("winner")
            checks.require(family_report.get("frozen_winner") == winner, "confirmation_winner_not_reselected", f"{shape_id}:{family}")
            candidates = family_report.get("candidates", [])
            expected_candidates = list(selected[family]["confirmation_candidates"])
            default = next(c for c in screen["campaign"]["experiments"]["GRID-screen"]["candidate_families"]["native"]
                           if not c.get("compiler_options"))
            if family == "native" and default["candidate_id"] not in {c["candidate_id"] for c in expected_candidates}:
                expected_candidates.append(default)
            checks.require([spec(c) for c in candidates] == [spec(c) for c in expected_candidates],
                           "confirmation_report_candidate_inventory", f"{shape_id}:{family}")
            for candidate in candidates:
                candidate_id = candidate["candidate_id"]
                is_headline = ((winner and candidate_id == winner["candidate_id"])
                               or (family == "native" and candidate_id == default["candidate_id"]))
                expected_group = f"{shape_id}__" + ("headline_confirmation" if is_headline else f"finalist_{family}_{candidate_id}")
                checks.require(candidate.get("group_id") == expected_group, "finalist_pair_group", f"{shape_id}:{candidate_id}")
                observed = eligible_scopes(confirmation, shape_id, family, candidate_id, expected_group)
                reference = (eligible_scopes(confirmation, shape_id, family, winner["candidate_id"], expected_group)
                             if winner else None)
                checks.require(candidate.get("confirmed_eligible") is (observed is not None)
                               and candidate.get("reference_available") is (reference is not None),
                               "confirmation_candidate_eligibility", f"{shape_id}:{candidate_id}")
                expected_scopes = set(SCOPES) if observed and reference else set()
                checks.require(set(candidate.get("scopes", {})) == expected_scopes,
                               "confirmation_pair_eligible_scopes", f"{shape_id}:{candidate_id}")
                for scope, pair in candidate.get("scopes", {}).items():
                    if not winner:
                        continue
                    pair_contract(pair, candidate_samples(confirmation, expected_group, winner["candidate_id"], scope),
                                  candidate_samples(confirmation, expected_group, candidate_id, scope), checks,
                                  f"{shape_id}:{candidate_id}:{scope}", inverse=True)
                    checks.require(close(pair.get("mean_ms"), observed[scope]["timing"]["mean_ms"]) if observed else False,
                                   "confirmation_pair_latency", f"{shape_id}:{candidate_id}:{scope}")
                    verified_pairs += 1
            for scope in SCOPES:
                measured = [candidate for candidate in candidates if scope in candidate.get("scopes", {})]
                near = family_report.get("near_sets", {}).get(scope, {})
                for percent in (1, 3, 5):
                    intended = tile_projection([candidate for candidate in measured
                                                if candidate["scopes"][scope]["latency_ratio_to_frozen_winner"] <= 1 + percent / 100])
                    checks.require(near.get(f"descriptive_{percent}_percent") == intended,
                                   "near_set_discrete_projection", f"{shape_id}:{family}:{scope}:{percent}")
                intended = tile_projection([candidate for candidate in measured if candidate["scopes"][scope]["certified_within_5_percent"]])
                checks.require(near.get("pointwise_ci95_certified_5_percent") == intended,
                               "near_set_interval_projection", f"{shape_id}:{family}:{scope}")
        headline_group = f"{shape_id}__headline_confirmation"
        available = [(family, candidate) for family, candidate in expected[headline_group]
                     if eligible_scopes(confirmation, shape_id, family, candidate["candidate_id"], headline_group)]
        expected_pairs = {(candidate["candidate_id"], reference["candidate_id"], scope)
                          for (_, candidate), (_, reference) in itertools.permutations(available, 2) for scope in SCOPES}
        pairs = shape_report.get("headline_comparisons", [])
        pair_keys = [(pair.get("candidate_id"), pair.get("reference_candidate_id"), pair.get("scope")) for pair in pairs]
        checks.require(set(pair_keys) == expected_pairs and len(pair_keys) == len(set(pair_keys)),
                       "headline_all_tuned_and_default_pairs", shape_id)
        for pair in pairs:
            checks.require(pair.get("group_id") == headline_group, "headline_pair_group", shape_id)
            headline_families = {candidate["candidate_id"]: family for family, candidate in expected[headline_group]}
            checks.require(pair.get("family") == headline_families.get(pair["candidate_id"])
                           and pair.get("reference_family") == headline_families.get(pair["reference_candidate_id"]),
                           "headline_pair_family_labels", shape_id)
            pair_contract(pair, candidate_samples(confirmation, headline_group, pair["reference_candidate_id"], pair["scope"]),
                          candidate_samples(confirmation, headline_group, pair["candidate_id"], pair["scope"]), checks,
                          f"{shape_id}:headline:{pair['candidate_id']}:{pair['reference_candidate_id']}:{pair['scope']}")
            verified_pairs += 1
    confirmation["report"]["verified_reported_pair_ratios"] = verified_pairs


def audit(screen_path, confirmation_path, manifest_path):
    checks = Checks()
    manifest = checks.load(manifest_path)
    reports = []
    try:
        if not isinstance(manifest, dict):
            raise ValueError("Shape manifest unreadable")
        exploratory = manifest["exploratory_shape_ids"]
        holdout = manifest["holdout_shape_ids"]
        checks.require(len(exploratory) == len(set(exploratory)) == 60
                       and len(holdout) == len(set(holdout)) == 12 and not set(exploratory) & set(holdout),
                       "manifest_60_exploratory_12_disjoint_holdouts", manifest_path)
        shape_ids = [row["id"] for row in manifest["shapes"]]
        checks.require(len(shape_ids) == len(set(shape_ids)) == 72 and set(shape_ids) == set(exploratory + holdout),
                       "manifest_geometry_inventory", manifest_path)
        checks.require(len({tuple(row[d] for d in ("m", "n", "k")) for row in manifest["shapes"]}) == 72,
                       "manifest_geometry_unique", manifest_path)
        screen = audit_phase(screen_path, "GRID-screen", manifest, checks)
        confirmation = audit_phase(confirmation_path, "GRID-confirm", manifest, checks)
        if screen:
            reports.append(screen["report"])
        if confirmation:
            reports.append(confirmation["report"])
        selection = audit_screen(screen, manifest, checks) if screen else None
        if screen and confirmation and selection:
            audit_confirmation(screen, confirmation, selection, manifest, manifest_path, checks)
    except (OSError, ValueError, KeyError, TypeError, IndexError, ZeroDivisionError) as error:
        checks.require(False, "audit_incomplete_due_to_malformed_evidence", f"{type(error).__name__}: {error}")
    return {"schema_version": 1, "audit_pass": not checks.issues,
            "inputs": {"screen": str(Path(screen_path).resolve()), "confirmation": str(Path(confirmation_path).resolve()),
                       "manifest": str(Path(manifest_path).resolve())},
            "manifest_sha256": sha(manifest_path) if Path(manifest_path).is_file() else None,
            "checks_performed": sum(checks.counts.values()), "check_counts_by_code": dict(checks.counts),
            "issue_count": len(checks.issues), "issues": checks.issues,
            "verified_files_sha256": checks.verified_files, "phases": reports,
            "scope": "Evidence integrity and internal consistency; scientific failures remain valid terminal observations.",
            "limitations": ["PCG64 bootstrap resamples and exact CI quantiles are not regenerated; round pairing, point ratios, interval bounds/order and near-set threshold transformations are checked.",
                            "Recorded compiler-option acceptance is audited, not the compiler's internal tile choice or utilization.",
                            "Host reference metadata and gate decisions are audited; original matrix products are not rerun.",
                            "Hash consistency does not prove external authenticity; Git history is not queried."]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--screen", type=Path, required=True)
    parser.add_argument("--confirmation", type=Path, required=True)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=False)
    report = audit(args.screen, args.confirmation, args.manifest)
    save(args.output_dir / "audit.json", report)
    lines = ["# Power/midpoint experiment evidence audit", "",
             f"**{'PASS' if report['audit_pass'] else 'FAIL'}** — {report['checks_performed']:,} checks; {report['issue_count']:,} issues.", "",
             "Compile, memory, and numerical failures are retained as outcomes. A passing audit does not establish an algorithmic speedup.", ""]
    for phase in report["phases"]:
        lines.extend([f"- {phase['phase']}: {phase['case_count']:,} terminal cases, {phase['sample_count']:,} raw samples, {phase['planned_groups']:,} planned groups.",
                      "  Terminal statuses: " + json.dumps(phase["case_status_counts"], sort_keys=True)])
    if report["issues"]:
        lines.extend(["", "## Evidence issues", ""])
        lines.extend(f"- `{item['code']}`: {item['detail']}" for item in report["issues"])
    lines.extend(["", "## Audit limits", ""])
    lines.extend(f"- {limitation}" for limitation in report["limitations"])
    with (args.output_dir / "summary.md").open("x") as stream:
        stream.write("\n".join(lines) + "\n")
    save(args.output_dir / "artifact_manifest.json", {
        "auditor_sha256": sha(Path(__file__)),
        "artifacts_sha256": {name: sha(args.output_dir / name) for name in ("audit.json", "summary.md")}})
    print(json.dumps({"audit_pass": report["audit_pass"], "checks_performed": report["checks_performed"],
                      "issue_count": report["issue_count"]}))
    return 0 if report["audit_pass"] else 1


